/**
 * GAM — Alloy emitter.
 *
 * Generates an Alloy model from a GAL-JSON law/enterprise pair. The emitted
 * module opens `gam_core` (alloy/gam_core.als) and therefore inherits exactly
 * the formalism of thesis §4.4 as revised: the ± polarity split, the closure
 * definitions, and pred Con.
 *
 * This closes the gap the 2009 thesis left open. Chapter 4 promised "sample
 * logic representations" of the GAL → Alloy translation and Chapter 6 promised
 * the mapping, but no Alloy source appears anywhere in the dissertation, and
 * the GAT prototype was never deposited. The translation was, until now, only
 * described.
 *
 * Two operators of §6.3 — Activity-Trace and Activity-Process-Trace — are
 * defined over transitive closure and are emitted as Alloy assertions over ^next.
 * They are NOT expressible in the propositional cross-check in sat-solver.js;
 * that is a property of propositional logic, not an omission here, and it is
 * why a relational analyser remains necessary.
 */

import { GamModel, UNRESTRICTED } from './model.js';

const ident = (s) => String(s).replace(/[^A-Za-z0-9_]/g, '_').replace(/^(\d)/, '_$1');
const list = (xs) => [...xs].map(ident).join(' + ');
const decl = (xs) => [...xs].map(ident).join(', ');   // sig declarations use commas

function group(map, keys) {
  const lines = [];
  for (const k of keys) {
    const vs = map.get(k);
    if (vs && vs.size) lines.push(`  ${ident(k)}.FIELD = ${list(vs)}`);
  }
  return lines;
}

/**
 * Emit `X.field = ...` for every key that has a value, then close the rest.
 * The closing line is always qualified by the owning sort: a bare `no next`
 * is ambiguous against Alloy's built-in integer/next.
 */
function emitField(map, field, allKeys, sort) {
  const lines = [];
  const used = [];
  for (const k of allKeys) {
    const vs = map.get(k);
    if (vs && vs.size) { lines.push(`  ${ident(k)}.${field} = ${list(vs)}`); used.push(k); }
  }
  const unused = allKeys.filter(k => !used.includes(k));
  if (unused.length) lines.push(`  no (${list(unused)}).${field}`);
  else if (!used.length && sort) lines.push(`  no ${sort}.${field}`);
  return lines;
}

/**
 * @param {Object} lawModel
 * @param {Object} enterpriseModel
 * @param {Object} opts { moduleName, scope, assertions: [{name, expr, comment}] }
 * @returns {string} Alloy source
 */
export function emitAlloy(lawModel = {}, enterpriseModel = {}, opts = {}) {
  const M = new GamModel(lawModel, enterpriseModel);
  const name = ident(typeof opts === 'string' ? opts : opts.moduleName || 'gam_generated');

  // collect the universe by sort
  const sorted = { Process: new Set(), Activity: new Set(), Role: new Set(), User: new Set() };
  for (const [id, sort] of M.sortOf) if (sorted[sort]) sorted[sort].add(id);
  // infer anything the entity list missed
  for (const p of M.processes)  sorted.Process.add(p);
  for (const a of M.activities) sorted.Activity.add(a);
  for (const r of M.roles)      sorted.Role.add(r);
  for (const u of M.users)      sorted.User.add(u);
  // an id can only belong to one sort; declared sort wins
  for (const [id, sort] of M.sortOf) {
    for (const s of Object.keys(sorted)) if (s !== sort) sorted[s].delete(id);
  }

  const P = [...sorted.Process], A = [...sorted.Activity];
  const R = [...sorted.Role],    U = [...sorted.User];

  const out = [];
  out.push(`module ${name}`);
  out.push(`open gam_core`);
  out.push('');
  out.push('/*');
  out.push(' * Generated by GAM (src/core/alloy-emitter.js). Do not edit by hand.');
  if (opts.title) out.push(` * ${opts.title}`);
  out.push(' *');
  out.push(' * Φ_L and Φ_E share one vocabulary and one universe. Legal prohibitions');
  out.push(' * populate the (−) relations and are therefore checked by Con; legal');
  out.push(' * structural requirements are emitted as assertions.');
  out.push(' */');
  out.push('');

  if (A.length) out.push(`one sig ${decl(A)} extends Activity {}`);
  if (P.length) out.push(`one sig ${decl(P)} extends Process {}`);
  if (R.length) out.push(`one sig ${decl(R)} extends Role {}`);
  if (U.length) out.push(`one sig ${decl(U)} extends User {}`);
  out.push('');

  out.push('fact ClosedWorld {');
  out.push(`  Activity = ${A.length ? list(A) : 'none'}`);
  out.push(`  Process  = ${P.length ? list(P) : 'none'}`);
  out.push(`  Role     = ${R.length ? list(R) : 'none'}`);
  out.push(`  User     = ${U.length ? list(U) : 'none'}`);
  out.push('}');
  out.push('');

  out.push('fact Ontology {');
  out.push(...emitField(M.PP, 'subProcess', P, 'Process'));
  out.push(...emitField(M.PA, 'activity', P, 'Process'));
  out.push(...emitField(M.RR, 'subRole', R, 'Role'));
  out.push(...emitField(M.S, 'next', A, 'Activity'));
  out.push(...emitField(M.X, 'sep', P, 'Process'));
  out.push('}');
  out.push('');

  out.push('fact Policy {');
  out.push(...emitField(M.RAp, 'mayDo', R, 'Role'));
  out.push(...emitField(M.RAm, 'mustNotDo', R, 'Role'));
  out.push(...emitField(M.RPp, 'mayReach', R, 'Role'));
  out.push(...emitField(M.RPm, 'mustNotReach', R, 'Role'));
  out.push(...emitField(M.UPp, 'mayAssume', U, 'User'));
  out.push(...emitField(M.UPm, 'mustNotAssume', U, 'User'));

  // RU is stored role → users; Alloy field mayAct is user → roles
  const RUpByUser = new Map(), RUmByUser = new Map();
  for (const [r, us] of M.RUp) for (const u of us) {
    if (!RUpByUser.has(u)) RUpByUser.set(u, new Set()); RUpByUser.get(u).add(r);
  }
  for (const [r, us] of M.RUm) for (const u of us) {
    if (!RUmByUser.has(u)) RUmByUser.set(u, new Set()); RUmByUser.get(u).add(r);
  }
  out.push(...emitField(RUpByUser, 'mayAct', U, 'User'));
  out.push(...emitField(RUmByUser, 'mustNotAct', U, 'User'));

  // delegation: Role -> (Role -> Delegable)
  const dTerms = (ds) => {
    const byFrom = new Map();
    for (const d of ds) {
      const tgt = d.target === UNRESTRICTED ? 'Unrestricted' : ident(d.target);
      if (!byFrom.has(d.from)) byFrom.set(d.from, []);
      byFrom.get(d.from).push(`(${ident(d.to)} -> ${tgt})`);
    }
    return byFrom;
  };
  const dp = dTerms(M.Dp), dm = dTerms(M.Dm);
  const emitDeleg = (byFrom, field) => {
    const lines = [], used = [];
    for (const [f, terms] of byFrom) { lines.push(`  ${ident(f)}.${field} = ${terms.join(' + ')}`); used.push(f); }
    const unused = R.filter(r => !used.includes(r));
    if (unused.length) lines.push(`  no (${list(unused)}).${field}`);
    else if (!used.length) lines.push(`  no Role.${field}`);
    return lines;
  };
  out.push(...emitDeleg(dp, 'mayDelegate'));
  out.push(...emitDeleg(dm, 'mustNotDelegate'));
  out.push('}');
  out.push('');

  const scope = (typeof opts === 'object' && opts.scope) || Math.max(10, A.length + P.length + 2);

  out.push('// ─── checks ───────────────────────────────────────────────────────────');
  out.push('');
  out.push('/** the baseline a per-relation review performs: does any single role');
  out.push(' *  carry a declared permit and a declared denial for one activity? */');
  out.push('pred DeclaredOnlyCheck { no r : Role | some (r.mayDo & r.mustNotDo) }');
  out.push(`check DeclaredOnlyCheckFindsNothing { DeclaredOnlyCheck } for ${scope}`);
  out.push('');
  out.push('/** Con( ⋀Φ_E ∧ ⋀Φ_L ) */');
  out.push(`check GAM_Con { Con } for ${scope}`);
  out.push('');

  const assertions = (typeof opts === 'object' && opts.assertions) || [];
  for (const a of assertions) {
    if (a.comment) out.push(`/** ${a.comment} */`);
    out.push(`assert ${ident(a.name)} { ${a.expr} }`);
    out.push(`check ${ident(a.name)} for ${scope}`);
    out.push('');
  }

  return out.join('\n');
}

export function generateAlloyModel(lawModel = {}, enterpriseModel = {}, moduleName = 'gam_generated') {
  return emitAlloy(lawModel, enterpriseModel, { moduleName });
}

/** Convenience: emit trace assertions for GAL Activity-Trace checks. */
export function traceAssertion(label, from, to) {
  return {
    name: ident(label),
    expr: `requiresPrecedence[${ident(from)}, ${ident(to)}]`,
    comment: `${label}: ${from} must eventually precede ${to}`,
  };
}

/** Convenience: emit an ontology-presence assertion. */
export function containsAssertion(label, process, activity) {
  return {
    name: ident(label),
    expr: `requiresActivity[${ident(process)}, ${ident(activity)}]`,
    comment: `${label}: process ${process} must contain activity ${activity}`,
  };
}

export default emitAlloy;
